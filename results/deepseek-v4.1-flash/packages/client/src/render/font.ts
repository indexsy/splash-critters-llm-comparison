const GLYPHS = new Map<string, string[]>();
for (const [key, value] of Object.entries(RAW)) GLYPHS.set(key, value.split("/"));

export const FONT_HEIGHT = 7;
export const FONT_ADVANCE = 6;

export function normalizeChar(char: string): string {
  const upper = char.toUpperCase();
  return GLYPHS.has(upper) ? upper : "?";
}

export function textWidth(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * FONT_ADVANCE - 1) * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  value: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow?: string,
): void {
  const text = value.toUpperCase();
  if (shadow) {
    drawRaw(ctx, text, x + scale, y + scale, shadow, scale);
  }
  drawRaw(ctx, text, x, y, color, scale);
}

function drawRaw(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale: number,
): void {
  ctx.fillStyle = color;
  let cursor = x;
  for (const char of text) {
    const glyph = GLYPHS.get(normalizeChar(char));
    if (glyph) {
      for (let row = 0; row < glyph.length; row += 1) {
        const bits = glyph[row]!;
        for (let col = 0; col < bits.length; col += 1) {
          if (bits[col] === "1") ctx.fillRect(cursor + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cursor += FONT_ADVANCE * scale;
  }
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  value: string,
  centerX: number,
  y: number,
  color: string,
  scale = 1,
  shadow?: string,
): void {
  drawText(ctx, value, Math.round(centerX - textWidth(value, scale) / 2), y, color, scale, shadow);
}

export function wrapText(value: string, maxWidth: number, scale = 1): string[] {
  const words = value.toUpperCase().split(/\s+/);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (textWidth(candidate, scale) > maxWidth && line) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }
  if (line) lines.push(line);
  return lines;
}
