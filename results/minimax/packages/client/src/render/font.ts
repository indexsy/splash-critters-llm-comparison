export const FONT_WIDTH = 5;
export const FONT_HEIGHT = 7;

export interface TextOptions {
  color?: string;
  shadow?: string;
  scale?: number;
  align?: 'left' | 'center' | 'right';
  spacing?: number;
}

export function textWidth(text: string, scale = 1, spacing = 1): number {
  if (text.length === 0) return 0;
  return (text.length * (FONT_WIDTH + spacing) - spacing) * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  options: TextOptions = {},
): void {
  const scale = options.scale ?? 1;
  const spacing = options.spacing ?? 1;
  const upper = text.toUpperCase();
  const width = textWidth(upper, scale, spacing);
  let originX = x;
  if (options.align === 'center') originX = Math.round(x - width / 2);
  if (options.align === 'right') originX = Math.round(x - width);

  const paint = (color: string, dx: number, dy: number) => {
    ctx.fillStyle = color;
    let cx = originX + dx;
    for (const ch of upper) {
      const glyph = GLYPHS[ch] ?? GLYPHS['?'];
      for (let row = 0; row < FONT_HEIGHT; row++) {
        const bits = glyph[row];
        for (let col = 0; col < FONT_WIDTH; col++) {
          if (bits & (1 << (FONT_WIDTH - 1 - col))) {
            ctx.fillRect(cx + col * scale, y + dy + row * scale, scale, scale);
          }
        }
      }
      cx += (FONT_WIDTH + spacing) * scale;
    }
  };

  if (options.shadow) paint(options.shadow, 0, scale);
  paint(options.color ?? '#fdf6e3', 0, 0);
}
